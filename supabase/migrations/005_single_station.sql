-- 005 · จุดจอดจักรยานทุกคันเป็นที่เดียว: "ป้อมB2 หอพักนิสิต"
-- แก้เฉพาะคอลัมน์ bikes.station (ทุกแถว) และตั้งค่าเริ่มต้นให้คันที่เพิ่มใหม่
-- ไม่ลบตาราง/แถวใด ไม่แตะสถานะหรือรายการยืม รันซ้ำได้
-- =====================================================================
update public.bikes
   set station = 'ป้อมB2 หอพักนิสิต'
 where station is distinct from 'ป้อมB2 หอพักนิสิต';

alter table public.bikes
  alter column station set default 'ป้อมB2 หอพักนิสิต';
